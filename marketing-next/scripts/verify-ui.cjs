const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.PREVIEW_URL || 'http://localhost:3210';
const artifacts = path.resolve('artifacts/visual-review');
fs.mkdirSync(artifacts, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  const checks = [];
  page.setDefaultTimeout(15000);
  try {
    for (const [name, width, height] of [['wide',1920,1080], ['desktop',1440,1000], ['laptop',1024,900], ['tablet',768,1024], ['mobile',390,844], ['narrow',320,740]]) {
      await page.setViewportSize({ width, height });
      const response = await page.goto(url, { waitUntil: 'networkidle' });
      assert.equal(response.status(),200);
      await page.evaluate(() => document.fonts.ready);
      assert.equal(await page.locator('h1').count(),1);
      const size = await page.evaluate(() => ({width:innerWidth, content:document.documentElement.scrollWidth}));
      assert.ok(size.content <= size.width, `${name}: horizontal overflow ${JSON.stringify(size)}`);
      const clipped = await page.locator('main h1, main p, main a, main button, main select').evaluateAll(nodes => nodes.flatMap(node => { const r=node.getBoundingClientRect(); return r.width && (r.left < -1 || r.right > innerWidth+1) ? [node.textContent.slice(0,60)] : []; }));
      assert.deepEqual(clipped, [], `${name}: clipped content`);
      await page.screenshot({ path:path.join(artifacts,`final-${name}.png`), fullPage:true });
      checks.push(`${name}: no horizontal overflow, rendered`);
    }
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(url,{waitUntil:'networkidle'});
    await page.getByRole('tab',{name:/Replay/}).click();
    await page.getByText('replay.case',{exact:true}).waitFor();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.getByRole('tab',{name:/Compare/}).getAttribute('aria-selected'),'true');
    await page.getByText('report.html',{exact:true}).waitFor();
    await page.getByRole('tab',{name:/Import/}).click();
    checks.push('Workflow stage explorer changes content and supports arrow-key navigation');
    for (const target of ['Anthropic','OpenAI','Ollama']) {
      await page.getByLabel('Target provider').selectOption(target);
      await page.getByRole('button',{name:'Run sample replay'}).click();
      assert.ok(await page.getByRole('button',{name:'Replaying'}).isDisabled());
      await page.getByText(`Illustrative results for ${target}`,{exact:true}).waitFor();
      assert.equal(await page.locator('[aria-live="polite"] [class*="verdict"]').count(),3);
    }
    await page.screenshot({path:path.join(artifacts,'final-replay.png')});
    checks.push('Three target selections replay; running and result states work');
    const firstCase=page.getByRole('button',{name:/Answer a support question/});
    await firstCase.click();
    assert.equal(await firstCase.getAttribute('aria-expanded'),'true');
    await page.getByText('Illustrative check',{exact:true}).waitFor();
    await page.screenshot({path:path.join(artifacts,'final-evidence.png')});
    await firstCase.click();
    checks.push('Replay evidence expands and collapses');
    await page.getByRole('button',{name:'Run demo',exact:true}).click();
    await page.getByRole('button',{name:'Copy',exact:true}).click();
    await page.getByRole('button',{name:'Copied',exact:true}).waitFor();
    const copied=await page.evaluate(()=>navigator.clipboard.readText());
    assert.ok(copied.includes('switchit.cli run --demo'));
    await page.getByRole('button',{name:'Install',exact:true}).click();
    await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('permission denied');}}}));
    await page.getByRole('button',{name:'Copy',exact:true}).click();
    await page.getByText('Select the command and copy it manually.').waitFor();
    checks.push('Install/demo command controls, successful clipboard and denied clipboard work');
    const download=page.getByRole('link',{name:'Download package'});
    const downloadResponse=await context.request.get(new URL(await download.getAttribute('href'),url).href);
    assert.equal(downloadResponse.status(),200);
    await page.setViewportSize({width:390,height:844});
    await page.goto(url,{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'Run sample replay'}).click();
    await page.getByText('Illustrative results for Anthropic',{exact:true}).waitFor();
    await page.getByRole('button',{name:/Look up an account/}).click();
    await page.locator('#demo [class*="preview"]').first().screenshot({path:path.join(artifacts,'final-replay-mobile.png')});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
    checks.push('Mobile replay and expanded evidence remain usable');
    await page.getByRole('button',{name:'Open menu'}).click();
    assert.ok(await page.getByRole('navigation',{name:'Mobile navigation'}).isVisible());
    await page.screenshot({path:path.join(artifacts,'final-mobile-menu.png')});
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded'),'false');
    await page.getByRole('button',{name:'Open menu'}).click();
    await page.getByRole('navigation',{name:'Mobile navigation'}).getByText('The report',{exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded'),'false');
    await page.waitForURL('**/#verdicts');
    checks.push('Mobile navigation opens, Escape closes it, anchor navigation closes it');
    const guide = await page.goto(`${url}/guide/`,{waitUntil:'networkidle'});
    assert.equal(guide.status(),200);
    assert.ok(await page.getByRole('link',{name:'Download v0.1.0 package'}).isVisible());
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path:path.join(artifacts,'final-guide-mobile.png'),fullPage:true});
    checks.push('Guide and package download available');
    assert.deepEqual(errors,[]);
    checks.push('No browser console errors or uncaught exceptions');
    fs.writeFileSync(path.join(artifacts,'checks.json'),JSON.stringify({url,checks},null,2));
    console.log(checks.join('\n'));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error); process.exitCode=1;});
